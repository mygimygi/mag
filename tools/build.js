// Builds every image asset + js/sprites.js metadata.  usage: node build.js [all|hero|weapon|mon|boss|fx|plat|bg]
const R = require('./render'), fs = require('fs'), path = require('path');
const hero = require('./art/hero'), weapon = require('./art/weapon'), mon = require('./art/monsters'), B = require('./art/bosses'), sc = require('./art/scene');
const IMG = path.resolve(__dirname, '../assets/img');
const what = process.argv[2] || 'all', want = k => what === 'all' || what === k;
const metaFile = path.resolve(__dirname, 'meta.json');
const meta = fs.existsSync(metaFile) ? JSON.parse(fs.readFileSync(metaFile)) : {};
(async () => {
  if (want('hero')) {
    const A = hero.anims(), frames = [], anims = {}, wx = [];
    for (const k of Object.keys(A)) { anims[k] = [frames.length, A[k].length]; for (const p of A[k]) { frames.push(hero.frame(p)); wx.push(hero.weaponXform(p)); } }
    meta.hero = Object.assign(await R.sheet(IMG + '/hero.png', hero.defs, frames, { w: 240, h: 200, ax: 140, ay: 190 }, 9, 2), { anims, wx, ws: hero.WS });
  }
  if (want('weapon')) {
    const frames = []; for (let on = 0; on < 2; on++) for (let b = 1; b <= 3; b++) for (let c = 1; c <= 3; c++) frames.push(weapon.weapon(b, c, on));
    meta.weapon = await R.sheet(IMG + '/weapon.png', weapon.defs, frames, { w: 180, h: 130, ax: 64, ay: 94 }, 6, 3);
  }
  if (want('mon')) {
    meta.mon = { anims: mon.ANIM, types: {} };
    for (const t of Object.keys(mon.M)) { const m = mon.M[t]; meta.mon.types[t] = await R.sheet(`${IMG}/m_${t}.png`, mon.defs, mon.frames(t), { w: m.cell[0], h: m.cell[1], ax: m.cell[0] / 2, ay: m.cell[1] - 12 }, 7, 2); meta.mon.types[t].bh = m.h; }
  }
  if (want('boss')) {
    meta.king = Object.assign(await R.sheet(IMG + '/king.png', B.defs, B.kingFrames(), { w: 240, h: 250, ax: 120, ay: 238 }, 6, 2), { anims: B.KING_ANIM });
    meta.titan = Object.assign(await R.sheet(IMG + '/titan.png', B.defs, B.titanFrames(), { w: 440, h: 500, ax: 220, ay: 490 }, 4, 1.5), { anims: B.TITAN_ANIM });
    meta.parts = Object.assign(await R.sheet(IMG + '/parts.png', B.defs, [B.fist(0), B.fist(1), B.shield(), B.pod(1), B.pod(0)], { w: 200, h: 160, ax: 100, ay: 80 }, 5, 2), { idx: { fist: 0, fistFast: 1, shield: 2, podOn: 3, podOff: 4 } });
  }
  if (want('fx')) meta.fx = Object.assign(await R.sheet(IMG + '/fx.png', B.defs, B.fx(), { w: 96, h: 96, ax: 48, ay: 48 }, 10, 2), { idx: B.FX });
  if (want('plat')) {
    for (const k of Object.keys(sc.THEMES)) {
      const p = sc.platformSheet(k), gr = sc.groundSheet(k);
      await R.shot(`${IMG}/plat_${k}.png`, `<svg xmlns="http://www.w3.org/2000/svg" width="${p.w}" height="${p.h}"><defs>${sc.themeDefs(k)}</defs>${p.svg}</svg>`, p.w, p.h, 2);
      await R.shot(`${IMG}/ground_${k}.png`, `<svg xmlns="http://www.w3.org/2000/svg" width="${gr.w}" height="${gr.h}"><defs>${sc.themeDefs(k)}</defs>${gr.svg}</svg>`, gr.w, gr.h, 2);
    }
    for (const k of ['cloud', 'spring', 'conveyor', 'wood']) { const q = sc.specialSheet(k); await R.shot(`${IMG}/plat_${k}.png`, `<svg xmlns="http://www.w3.org/2000/svg" width="${q.w}" height="${q.h}">${q.svg}</svg>`, q.w, q.h, 2); }
    meta.plat = { h: 72, top: 8, capW: 48, tileW: 96, groundH: 104, scale: 2 };
  }
  if (want('bg')) { for (let n = 1; n <= 16; n++) await R.shot(`${IMG}/bg${n}.jpg`, sc.background(n), 1280, 720, 1.25, '#fff', 86); meta.bg = { worlds: Object.fromEntries(Object.entries(sc.STAGES).map(([k, v]) => [k, v.world])) }; }
  fs.writeFileSync(metaFile, JSON.stringify(meta));
  fs.writeFileSync(path.resolve(__dirname, '../js/sprites.js'), '// generated by tools/build.js\nwindow.MP_SPRITES = ' + JSON.stringify(meta) + ';\n');
  await R.close();
})();
